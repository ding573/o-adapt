// One-time external-model request generator. It never sends the existing fixtures
// or route outputs to the generator, and refuses to overwrite a frozen holdout.
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('../../', import.meta.url);
const outputUrl = new URL('./cases.json', import.meta.url);
const metadataUrl = new URL('./generation-metadata.json', import.meta.url);
try {
  await fs.access(outputUrl);
  throw new Error('Holdout already exists; refusing to overwrite frozen cases.json.');
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

const envText = await fs.readFile(new URL('.env', root), 'utf8');
const configuredKey = envText.split(/\r?\n/).find(line => line.startsWith('OPENROUTER_API_KEY='))?.slice('OPENROUTER_API_KEY='.length).trim();
const apiKey = process.env.OPENROUTER_API_KEY || configuredKey;
if (!apiKey) throw new Error('OPENROUTER_API_KEY is not configured.');
const generatorModel = process.env.OPENROUTER_HOLDOUT_MODEL || 'google/gemini-2.5-flash';
const productionModel = process.env.OPENROUTER_MODEL || 'openai/gpt-4o-mini';
if (generatorModel === productionModel) throw new Error('Holdout generator must differ from the production model.');

const prompt = [
  'Create 30 diverse test requests for a recreational orienteering route generator in one fixed park.',
  'Return JSON only: {"requests":[{"targetDistanceM":integer,"difficulty":string,"controlCount":integer,"focus":string}]}',
  'Each request must have targetDistanceM from 600 to 1400 inclusive, controlCount 3 to 5,',
  'difficulty beginner/intermediate/advanced, and focus navigation/route-choice/physical.',
  'Use varied distances, especially non-round distances, all difficulty and focus categories,',
  'and distinct combinations. Do not assume any requested route is feasible.',
  'You have not seen the application, existing fixtures, routes, or outcomes.',
].join(' ');

const response = await fetch('https://openrouter.ai/api/v1/chat/completions', {
  method: 'POST',
  signal: AbortSignal.timeout(60000),
  headers: {
    Authorization: `Bearer ${apiKey}`,
    'Content-Type': 'application/json',
    'HTTP-Referer': 'http://localhost:3000',
    'X-Title': 'O-Adapt external holdout generation',
  },
  body: JSON.stringify({
    model: generatorModel,
    temperature: 0.9,
    max_tokens: 3500,
    response_format: { type: 'json_object' },
    messages: [
      { role: 'system', content: 'You generate test requests only. Do not score or predict the system output.' },
      { role: 'user', content: prompt },
    ],
  }),
});
const payload = await response.json();
if (!response.ok) throw new Error(`Holdout generation failed: ${payload?.error?.message || response.status}`);
const content = payload.choices?.[0]?.message?.content;
if (typeof content !== 'string') throw new Error('Generator returned no text.');
const parsed = JSON.parse(content.trim().replace(/^```json\s*/i, '').replace(/```$/i, '').trim());
if (!Array.isArray(parsed.requests)) throw new Error('Generator did not return requests.');

const original = JSON.parse(await fs.readFile(new URL('../cases.json', import.meta.url), 'utf8'));
const originalKeys = new Set(original.cases.map(item => JSON.stringify(item.request)));
const seen = new Set();
const accepted = [];
for (const request of parsed.requests) {
  const valid = Number.isInteger(request?.targetDistanceM) && request.targetDistanceM >= 600 && request.targetDistanceM <= 1400
    && Number.isInteger(request?.controlCount) && request.controlCount >= 3 && request.controlCount <= 5
    && ['beginner', 'intermediate', 'advanced'].includes(request?.difficulty)
    && ['navigation', 'route-choice', 'physical'].includes(request?.focus);
  if (!valid) continue;
  const canonical = { targetDistanceM: request.targetDistanceM, difficulty: request.difficulty, controlCount: request.controlCount, focus: request.focus };
  const key = JSON.stringify(canonical);
  if (seen.has(key) || originalKeys.has(key)) continue;
  seen.add(key);
  accepted.push(canonical);
  if (accepted.length === 20) break;
}
if (accepted.length !== 20) throw new Error(`Only ${accepted.length} valid unseen requests were returned; no holdout was written.`);
for (const field of ['difficulty', 'focus']) {
  if (new Set(accepted.map(request => request[field])).size !== 3) throw new Error(`Holdout does not cover all ${field} values.`);
}
const cases = {
  version: 1,
  provenance: `Generated by ${generatorModel} without access to the original fixtures or route outputs; frozen before route evaluation. Request generation alone does not supply ground-truth feasibility or quality labels.`,
  cases: accepted.map((request, index) => ({ id: `H${String(index + 1).padStart(2, '0')}`, group: 'external_holdout', request })),
};
const fixtureText = JSON.stringify(cases, null, 2) + '\n';
await fs.writeFile(outputUrl, fixtureText, { flag: 'wx' });
await fs.writeFile(metadataUrl, JSON.stringify({ generated_at: new Date().toISOString(), requested_generator_model: generatorModel, returned_generator_model: payload.model || null, production_model: productionModel, source_prompt_sha256: createHash('sha256').update(prompt).digest('hex'), fixture_sha256: createHash('sha256').update(fixtureText).digest('hex'), provider_usage: payload.usage || null }, null, 2) + '\n');
console.log(JSON.stringify({ cases: cases.cases.length, generator_model: payload.model || generatorModel, fixture_sha256: createHash('sha256').update(fixtureText).digest('hex'), reported_cost_usd: payload.usage?.cost ?? null }, null, 2));
